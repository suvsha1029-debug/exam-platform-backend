package com.shashwat.examplatformbackend.student;

import java.time.Instant;
import java.time.LocalDate;
import java.util.List;
import java.util.Map;

public record CandidateDashboardResponse(
        String registrationId,
        String examCode,
        String examName,
        int durationMinutes,
        String streamCode,
        boolean correctionsOpen,
        String fullName,
        LocalDate dateOfBirth,
        String email,
        String alternateEmail,
        String phone,
        String address,
        String state,
        String pincode,
        String nationality,
        String gender,
        String parentName,
        String parentPhone,
        String guardianName,
        String guardianPhone,
        String guardianRelation,
        String ugDetails,
        String pgDetails,
        boolean photoUploaded,
        boolean signatureUploaded,
        String photoPath,
        String signaturePath,
        boolean idCardUploaded,
        String idCardPath,
        boolean class10MarksheetUploaded,
        boolean class12MarksheetUploaded,
        boolean ugDocumentUploaded,
        boolean pgDocumentUploaded,
        Map<String, String> customFieldValues,
        Map<String, String> customFilePaths,
        Map<String, String> candidateCorrectionFields,
        boolean examLobbyAvailable,
        boolean questionPaperUploaded,
        boolean examLaunchEnabled,
        boolean candidateSubmitEnabled,
        boolean responsesReleased,
        boolean resultReleased,
        boolean originalQuestionPaperReleased,
        boolean originalAnswerKeyReleased,
        boolean scoreCardPdfReleased,
        boolean answerKeyChallengeEnabled,
        Instant answerKeyChallengeOpensAt,
        Instant answerKeyChallengeClosesAt,
        List<String> allowedCountryIso2s,
        String originalQuestionPaperPdfName,
        String originalAnswerKeyPdfName,
        boolean responseSubmitted,
        Instant examStartAt,
        int loginOpensMinutesBeforeStart,
        int loginClosesMinutesBeforeStart,
        boolean examReadinessTimerEnabled,
        int examReadinessDurationSeconds,
        String examAccessMessage,
        Instant createdAt,
        boolean resultWithheld
) {
    static CandidateDashboardResponse from(Student student, String examName, boolean correctionsOpen) {
        return from(student, examName, 180, correctionsOpen, Map.of(), false, false, false, false, false, false, false, false, false, false, null, null, List.of(), null, null, false, null, 30, 15, true, 120, "");
    }

    static CandidateDashboardResponse from(Student student, String examName, boolean correctionsOpen, Map<String, String> candidateCorrectionFields) {
        return from(student, examName, 180, correctionsOpen, candidateCorrectionFields, false, false, false, false, false, false, false, false, false, false, null, null, List.of(), null, null, false, null, 30, 15, true, 120, "");
    }

    static CandidateDashboardResponse from(Student student, String examName, int durationMinutes, boolean correctionsOpen, Map<String, String> candidateCorrectionFields, boolean examLobbyAvailable, boolean questionPaperUploaded, boolean examLaunchEnabled, boolean candidateSubmitEnabled, boolean responsesReleased, boolean resultReleased, boolean originalQuestionPaperReleased, boolean originalAnswerKeyReleased, boolean scoreCardPdfReleased, boolean answerKeyChallengeEnabled, Instant answerKeyChallengeOpensAt, Instant answerKeyChallengeClosesAt, List<String> allowedCountryIso2s, String originalQuestionPaperPdfName, String originalAnswerKeyPdfName, boolean responseSubmitted, Instant examStartAt, int loginOpensMinutesBeforeStart, int loginClosesMinutesBeforeStart, boolean examReadinessTimerEnabled, int examReadinessDurationSeconds, String examAccessMessage) {
        return new CandidateDashboardResponse(
                student.getRegistrationId(),
                student.getExamCode(),
                examName,
                durationMinutes,
                student.getStreamCode(),
                correctionsOpen,
                student.getFullName(),
                student.getDateOfBirth(),
                student.getEmail(),
                student.getAlternateEmail(),
                student.getPhone(),
                student.getAddress(),
                student.getState(),
                student.getPincode(),
                student.getNationality(),
                student.getGender(),
                student.getParentName(),
                student.getParentPhone(),
                student.getGuardianName(),
                student.getGuardianPhone(),
                student.getGuardianRelation(),
                student.getUgDetails(),
                student.getPgDetails(),
                student.getPhotoPath() != null,
                student.getSignaturePath() != null,
                student.getPhotoPath(),
                student.getSignaturePath(),
                student.getIdCardPath() != null,
                student.getIdCardPath(),
                student.getClass10MarksheetPath() != null,
                student.getClass12MarksheetPath() != null,
                student.getUgDocumentPath() != null,
                student.getPgDocumentPath() != null,
                CandidateCustomDataMapper.toStringMap(student.getCustomFieldValuesJson()),
                CandidateCustomDataMapper.toStringMap(student.getCustomFilePathsJson()),
                candidateCorrectionFields == null ? Map.of() : candidateCorrectionFields,
                examLobbyAvailable,
                questionPaperUploaded,
                examLaunchEnabled,
                candidateSubmitEnabled,
                responsesReleased,
                resultReleased && !student.isResultWithheld(),
                originalQuestionPaperReleased,
                originalAnswerKeyReleased,
                scoreCardPdfReleased && !student.isResultWithheld(),
                answerKeyChallengeEnabled,
                answerKeyChallengeOpensAt,
                answerKeyChallengeClosesAt,
                allowedCountryIso2s == null ? List.of() : List.copyOf(allowedCountryIso2s),
                originalQuestionPaperPdfName,
                originalAnswerKeyPdfName,
                responseSubmitted,
                examStartAt,
                loginOpensMinutesBeforeStart,
                loginClosesMinutesBeforeStart,
                examReadinessTimerEnabled,
                examReadinessDurationSeconds,
                examAccessMessage,
                student.getCreatedAt(),
                student.isResultWithheld()
        );
    }
}
