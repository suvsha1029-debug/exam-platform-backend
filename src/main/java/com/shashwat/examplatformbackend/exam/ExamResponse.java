    private static int estimateTemplateCount(Exam exam) {
        String library = exam.getReportCardTemplatesJson();
        if (library == null || library.isBlank()) {
            return exam.getReportCardTemplateJson() == null ? 0 : 1;
        }
        int count = 0;
        for (int index = 0; index < library.length(); index++) {
            if (library.startsWith("\"templateId\"", index)) {
                count++;
            }
        }
        return Math.max(count, exam.getReportCardTemplateJson() == null ? 0 : 1);
    }
