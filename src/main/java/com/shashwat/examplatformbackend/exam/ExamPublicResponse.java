package com.shashwat.examplatformbackend.exam;

import java.util.List;
import java.util.Map;

public record ExamPublicResponse(
        String examCode,
        String name,
        int durationMinutes,
        boolean active,
        boolean registrationOpen,
        boolean correctionsOpen,
        boolean streamSelectionRequired,
        String portalNotification,
        String portalNotifications,
        String portalNotificationBadgeStyle,
        boolean portalNoticeTabEnabled,
        String portalNoticeDocumentLabel,
        boolean portalNoticePdfUploaded,
        String portalWelcomeText,
        String portalHeaderTitle,
        String portalHeaderSubtitle,
        String portalHeaderTextColor,
        String portalHeaderBackgroundColor,
        String portalNotificationTextColor,
        String portalNotificationBackgroundColor,
        String portalNotificationFontSize,
        String portalHeroImageUrl,
        String portalTopBannerImageUrl,
        String portalPageBackgroundImageUrl,
        String portalWelcomeTextColor,
        String examUiHeaderTitle,
        String examUiHeaderSubtitle,
        String examUiBannerImageUrl,
        boolean desktopEntryTimerEnabled,
        int desktopEntryDelaySeconds,
        boolean desktopCaptureProtectionEnabled,
        boolean examReadinessTimerEnabled,
        int examReadinessDurationSeconds,
        List<CustomCandidateField> customFields,
        Map<String, String> candidateFieldSteps,
        Map<String, String> candidateRequiredFields,
        List<String> allowedCountryIso2s,
        List<ExamStreamResponse> streams,
        List<CandidateField> enabledFields,
        PortalSupportContent portalSupportContent,
        List<PortalNotice> portalNotices
) {
    static ExamPublicResponse from(Exam exam) {
        return new ExamPublicResponse(
                exam.getExamCode(),
                exam.getName(),
                exam.getDurationMinutes(),
                exam.isActive(),
                exam.isRegistrationOpen(),
                exam.isCorrectionsOpen(),
                exam.isStreamSelectionRequired(),
                exam.getPortalNotification(),
                exam.getPortalNotifications(),
                exam.getPortalNotificationBadgeStyle(),
                exam.isPortalNoticeTabEnabled(),
                exam.getPortalNoticeDocumentLabel(),
                exam.getPortalNoticePdfPath() != null,
                exam.getPortalWelcomeText(),
                exam.getPortalHeaderTitle(),
                exam.getPortalHeaderSubtitle(),
                exam.getPortalHeaderTextColor(),
                exam.getPortalHeaderBackgroundColor(),
                exam.getPortalNotificationTextColor(),
                exam.getPortalNotificationBackgroundColor(),
                exam.getPortalNotificationFontSize(),
                exam.getPortalHeroImageUrl(),
                exam.getPortalTopBannerImageUrl(),
                exam.getPortalPageBackgroundImageUrl(),
                exam.getPortalWelcomeTextColor(),
                exam.getExamUiHeaderTitle(),
                exam.getExamUiHeaderSubtitle(),
                exam.getExamUiBannerImageUrl(),
                exam.isDesktopEntryTimerEnabled(),
                exam.getDesktopEntryDelaySeconds(),
                exam.isDesktopCaptureProtectionEnabled(),
                exam.isExamReadinessTimerEnabled(),
                exam.getExamReadinessDurationSeconds(),
                CustomCandidateFieldJson.parse(exam.getCustomFieldsJson()),
                CustomCandidateFieldJson.parseStringMap(exam.getCandidateFieldStepConfigJson()),
                CustomCandidateFieldJson.parseStringMap(exam.getCandidateRequiredFieldsJson()),
                CustomCandidateFieldJson.parseStringList(exam.getAllowedCountryIso2sJson()),
                exam.getStreams().stream().map(ExamStreamResponse::from).toList(),
                List.copyOf(exam.getEnabledFields()),
                PortalSupportContent.fromJson(exam.getPortalSupportContentJson()),
                exam.getPortalNotices()
        );
    }
}
